"""Package .claude/ skills, agents and hooks as the `slm-sdlc` Claude Code plugin.

.claude/ is the source of truth (it's what Claude Code loads in this repo, including
cloud sessions). This script copies it into plugins/slm-sdlc/ so other repos can
install the same workflow from this repo's marketplace.

Usage:
    python scripts/build_plugin.py          # regenerate plugins/slm-sdlc/
    python scripts/build_plugin.py --check  # exit 1 if the plugin is out of date (CI)
"""

from __future__ import annotations

import argparse
import filecmp
import json
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / ".claude"
DEST = ROOT / "plugins" / "slm-sdlc"

MANIFEST = {
    "name": "slm-sdlc",
    "version": "0.1.0",
    "description": "Agentic SDLC for ML projects: spec, ADR, experiment, evaluation and ship skills, plus ML and architecture reviewer agents.",
    "author": {"name": "mkapileo12"},
    "repository": "https://github.com/mkapileo12/slm-from-scratch",
    "license": "MIT",
}

HOOKS = {
    "hooks": {
        "PostToolUse": [
            {
                "matcher": "Edit|Write",
                "hooks": [{"type": "command", "command": 'python3 "${CLAUDE_PLUGIN_ROOT}/hooks/check_python.py"'}],
            }
        ]
    }
}


def build(dest: Path) -> None:
    if dest.exists():
        shutil.rmtree(dest)
    (dest / ".claude-plugin").mkdir(parents=True)
    (dest / ".claude-plugin" / "plugin.json").write_text(json.dumps(MANIFEST, indent=2) + "\n")
    shutil.copytree(SRC / "skills", dest / "skills")
    shutil.copytree(SRC / "agents", dest / "agents")
    (dest / "hooks").mkdir()
    shutil.copy2(SRC / "hooks" / "check_python.py", dest / "hooks" / "check_python.py")
    (dest / "hooks" / "hooks.json").write_text(json.dumps(HOOKS, indent=2) + "\n")
    (dest / "README.md").write_text(
        "# slm-sdlc plugin\n\nGenerated by `scripts/build_plugin.py` from `.claude/`. Do not edit by hand.\n"
        "See `docs/sdlc.md` in the repository for the workflow.\n"
    )


def same_tree(a: Path, b: Path) -> bool:
    cmp = filecmp.dircmp(a, b)
    if cmp.left_only or cmp.right_only or cmp.funny_files:
        return False
    _, mismatch, errors = filecmp.cmpfiles(a, b, cmp.common_files, shallow=False)
    if mismatch or errors:
        return False
    return all(same_tree(a / d, b / d) for d in cmp.common_dirs)


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--check", action="store_true")
    args = p.parse_args()
    if args.check:
        with tempfile.TemporaryDirectory() as tmp:
            fresh = Path(tmp) / "slm-sdlc"
            build(fresh)
            if not DEST.exists() or not same_tree(fresh, DEST):
                print("plugins/slm-sdlc is out of date: run python scripts/build_plugin.py", file=sys.stderr)
                sys.exit(1)
        print("plugin up to date")
    else:
        build(DEST)
        print(f"built {DEST.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
